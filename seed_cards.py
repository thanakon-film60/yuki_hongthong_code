def ensure_schema(db):
    db.execute("""CREATE TABLE IF NOT EXISTS cards(
        id TEXT PRIMARY KEY, name_full TEXT NOT NULL, name_short TEXT, effect TEXT,
        category TEXT, rarity TEXT, width_cm REAL, height_cm REAL, prices TEXT,
        image_file TEXT, phash TEXT, dhash TEXT, created_at TEXT)""")
    # ทำเครื่องหมายว่าแถวไหนมาจาก seed เพื่อรันซ้ำได้สะอาด
    cols = [r[1] for r in db.execute("PRAGMA table_info(cards)")]
    if "seeded" not in cols:
        db.execute("ALTER TABLE cards ADD COLUMN seeded INTEGER DEFAULT 0")
    if "edition" not in cols:
        db.execute("ALTER TABLE cards ADD COLUMN edition TEXT")

def main():
    db = sqlite3.connect(DB)
    ensure_schema(db)
    db.execute("DELETE FROM cards WHERE seeded=1")  # ล้าง seed เก่า

    added = 0
    for fname, th, jp, effect, cat, price in DATA:
        src = os.path.join(IMG_DIR, fname)
        if not os.path.exists(src):
            print("  ! ไม่พบไฟล์:", fname); continue
        # คัดลอกรูปเข้า static/uploads เพื่อให้เว็บแสดงได้
        dst_name = fname
        dst = os.path.join(UPLOAD_DIR, dst_name)
        if not os.path.exists(dst):
            with Image.open(src) as im:
                im.convert("RGB").save(dst, "JPEG", quality=85)
        with Image.open(dst) as im:
            rgb = im.convert("RGB")
            ph, dh = str(imagehash.phash(rgb)), str(imagehash.dhash(rgb))
        cid = uuid.uuid4().hex[:12]
        edition = EDITIONS.get(fname, "")
        db.execute("""INSERT INTO cards
            (id,name_full,name_short,effect,category,rarity,edition,width_cm,height_cm,prices,image_file,phash,dhash,created_at,seeded)
            VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,1)""",
            (cid, th, jp, effect, cat, "Yu-Gi-Oh! JP", edition, STD_W, STD_H,
             json.dumps([{"source": "ป้ายราคาในรูป", "price": price}], ensure_ascii=False),
             dst_name, ph, dh, datetime.now().isoformat(timespec="seconds")))
        added += 1
        print(f"  + {th}  ({price}฿)  [{edition}]")

    db.commit(); db.close()
    print(f"\nเสร็จ! เพิ่ม {added} การ์ดเข้าคลังแล้ว — รัน  python app.py  แล้วเปิดเว็บเพื่อสแกน/ตรวจสอบ")

if __name__ == "__main__":
    main()
